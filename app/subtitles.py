"""Safe, predictable FFmpeg subtitle filter construction."""
from pathlib import Path
from typing import Literal


def build_subtitle_filter(
    subtitle_file: Path,
    font_size: int = 36,
    position: Literal["bottom", "middle", "top"] = "bottom",
    color: Literal["white", "yellow"] = "white",
) -> str:
    if not 20 <= font_size <= 64:
        raise ValueError("Subtitle font size must be between 20 and 64.")
    alignment = {"bottom": 2, "middle": 5, "top": 8}.get(position)
    if alignment is None:
        raise ValueError("Unsupported subtitle position.")
    primary = {"white": "&H00FFFFFF", "yellow": "&H0000FFFF"}.get(color)
    if primary is None:
        raise ValueError("Unsupported subtitle color.")
    # The filename is generated by the application, never supplied by the user.
    path = str(subtitle_file)
    return (
        f"subtitles=filename={path}:force_style="
        f"'FontName=Noto Sans Tamil,FontSize={font_size},PrimaryColour={primary},"
        f"OutlineColour=&H00000000,BorderStyle=1,Outline=2,Shadow=1,"
        f"Alignment={alignment},MarginV=60'"
    )
